import Testing
import Observation

// This class represents the exact hand-written expansion of what the @Observable
// macro currently produces. It has NO @Observable or @ObservationTracked attributes,
// only the manually-written generated code that pins down compatibility.
// This ensures that code compiled against an old binary's macro output continues
// to work with the current runtime, independent of future macro changes.

final class LegacyExpansionFixture: Observation.Observable {
  // Registrar variable - same name and pattern the macro generates
  @ObservationIgnored private let _$observationRegistrar = Observation.ObservationRegistrar()
  
  // Storage for the tracked property
  private var _value: Int = 0
  
  // Generated access function
  internal nonisolated func access<Member>(
    keyPath: KeyPath<LegacyExpansionFixture, Member>
  ) {
    _$observationRegistrar.access(self, keyPath: keyPath)
  }
  
  // Generated withMutation function
  internal nonisolated func withMutation<Member, MutationResult>(
    keyPath: KeyPath<LegacyExpansionFixture, Member>,
    _ mutation: () throws -> MutationResult
  ) rethrows -> MutationResult {
    try _$observationRegistrar.withMutation(of: self, keyPath: keyPath, mutation)
  }
  
  // Generated shouldNotifyObservers overloads
  private nonisolated final func shouldNotifyObservers<Member>(_ lhs: Member, _ rhs: Member) -> Bool { true }
  
  private nonisolated final func shouldNotifyObservers<Member: Equatable>(_ lhs: Member, _ rhs: Member) -> Bool { lhs != rhs }
  
  private nonisolated final func shouldNotifyObservers<Member: AnyObject>(_ lhs: Member, _ rhs: Member) -> Bool { lhs !== rhs }
  
  private nonisolated final func shouldNotifyObservers<Member: Equatable & AnyObject>(_ lhs: Member, _ rhs: Member) -> Bool { lhs != rhs }
  
  // Property accessors generated by @ObservationTracked
  var value: Int {
    @storageRestrictions(initializes: _value)
    init(initialValue) {
      _value = initialValue
    }
    
    get {
      access(keyPath: \.value)
      return _value
    }
    
    set {
      guard shouldNotifyObservers(_value, newValue) else {
        _value = newValue
        return
      }
      withMutation(keyPath: \.value) {
        _value = newValue
      }
    }
    
    _modify {
      access(keyPath: \.value)
      _$observationRegistrar.willSet(self, keyPath: \.value)
      defer { _$observationRegistrar.didSet(self, keyPath: \.value) }
      yield &_value
    }
  }
  
  init(value: Int = 0) {
    self.value = value
  }
}

// Tests for the legacy expansion fixture
@Test func mutatePropertyTriggesNotification() async {
  let changed = CapturedState(state: false)
  let fixture = LegacyExpansionFixture(value: 42)
  
  withObservationTracking {
    _ = fixture.value
  } onChange: {
    changed.state = true
  }
  
  fixture.value = 100
  #expect(changed.state == true)
}

@Test func observePropertyWithWillSetCallback() async {
  let changeCount = CapturedState(state: 0)
  let fixture = LegacyExpansionFixture(value: 10)
  
  withObservationTracking(options: .willSet) {
    _ = fixture.value
  } onChange: { _ in
    changeCount.state += 1
  }
  
  fixture.value = 20
  #expect(changeCount.state == 1)
}

@Test func observePropertyWithDidSetCallback() async {
  let changeCount = CapturedState(state: 0)
  let fixture = LegacyExpansionFixture(value: 10)
  
  withObservationTracking(options: .didSet) {
    _ = fixture.value
  } onChange: { _ in
    changeCount.state += 1
  }
  
  fixture.value = 20
  #expect(changeCount.state == 1)
}

@Test func willSetAndDidSetCallbacksBoth() async {
  let changeCount = CapturedState(state: 0)
  let fixture = LegacyExpansionFixture(value: 10)
  
  withObservationTracking(options: [.willSet, .didSet]) {
    _ = fixture.value
  } onChange: { _ in
    changeCount.state += 1
  }
  
  fixture.value = 20
  // Both willSet and didSet trigger callbacks
  #expect(changeCount.state == 2)
}

@Test func noNotificationWhenValueUnchanged() async {
  let changed = CapturedState(state: false)
  let fixture = LegacyExpansionFixture(value: 42)
  
  withObservationTracking {
    _ = fixture.value
  } onChange: {
    changed.state = true
  }
  
  // Set to same value (Int is Equatable)
  fixture.value = 42
  #expect(changed.state == false)
}

@Test func keyPathTrackedCorrectly() async {
  let trackedKeyPath = CapturedState<PartialKeyPath<LegacyExpansionFixture>?>(state: nil)
  let fixture = LegacyExpansionFixture(value: 5)
  
  withObservationTracking {
    _ = fixture.value
  } onChange: {
    trackedKeyPath.state = \.value
  }
  
  fixture.value = 10
  #expect(trackedKeyPath.state == \.value)
}

